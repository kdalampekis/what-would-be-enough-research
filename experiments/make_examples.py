"""Worked examples for docs/EXAMPLES.md: real items with the prompt, the model's answer, the oracle's label
and the score. Presentation only; nothing here is an analysis.

Selection rule (fixed, so the examples are not hand-picked): for each case, the first item in sorted
instance-id order that meets the stated condition for the stated model.

    python experiments/make_examples.py            # needs the raw responses under results/raw/pilot
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import analyze_t1  # noqa: E402
from run_eop import planned_results  # noqa: E402

from msep.controllers.llm_extractor import extraction_prompt, extraction_prompt_v2  # noqa: E402
from msep.eval import pilot  # noqa: E402
from msep.models.runner import Job, latest_record, load_results  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "results" / "raw" / "pilot"
DATA = ROOT / "data" / "generated" / "pool_v3" / "instances.jsonl"
T1 = ROOT / "data" / "generated" / "t1_v1" / "pairs.jsonl"
Q35, DS = "adaption-qwen3.5-397b", "adaption-deepseek-v4-flash"


def short_state(text: str) -> str:
    out = []
    for line in text.splitlines():
        if re.match(r"\s+K\d+: ", line) and len(line) > 150:
            line = line[:140] + " […]"
        out.append(line)
    text = "\n".join(out)
    cut = text.find("Information actions (ASK_...)")
    return text[:cut].rstrip() + "\n[closing paragraph omitted]" if cut > 0 else text


def answer(rec: dict) -> str:
    p = rec.get("parsed")
    if p is None:
        return f"(no parsed answer: {rec.get('parse_error')})"
    keep = {k: p[k] for k in ("state_sufficient", "resource_class", "plan", "decision", "short_justification") if k in p}
    return json.dumps(keep, indent=1, ensure_ascii=False)


def oracle(rec: dict) -> str:
    o, alias = rec["oracle"], rec["rendering"]["action_alias"]
    plans = [", ".join(alias.get(a, a) for a in pl) or "(empty plan)" for pl in o["optimal_plans"][:2]]
    return (f"class **{o['resource_class']}**; cheapest sufficient plan: "
            f"{' or '.join(plans) if plans else 'none exists'}; cost {o['optimal_cost']}")


def block(title: str, how: str, rec: dict, parts: list[tuple[str, str]], reading: str) -> str:
    lines = [f"## {title}", "", f"*How it was chosen:* {how}", "",
             f"**Item** `{rec['instance_id']}` (dev split). **Oracle:** {oracle(rec)}.", "",
             "<details><summary>The state as the model saw it</summary>", "", "```text", short_state(rec["prompt_text"]),
             "```", "", "</details>", ""]
    for head, body in parts:
        lines += [f"**{head}**", "", "```text", body, "```", ""]
    lines += [f"**What this shows.** {reading}", ""]
    return "\n".join(lines)


def eop_answer(rec: dict, key: str, pool: str, fn) -> str:
    ex = latest_record(RAW, Job(pool, rec["instance_id"], rec["family_id"], "extraction", fn(rec["prompt_text"])), key)
    if ex is None:
        return "(no extraction on file)"
    res, _ = planned_results([rec], {rec["instance_id"]: ex})
    p = res[0].get("parsed")
    return "(extraction invalid: planner did not run)" if p is None else json.dumps(
        {k: p[k] for k in ("state_sufficient", "resource_class", "plan", "decision")}, indent=1)


def main() -> int:
    dev = {r["instance_id"]: r for r in pilot.load_records(DATA, ("dev",), None)}
    t1 = {r["instance_id"]: r for r in analyze_t1.select_t1(DATA, T1, ("dev",), 30, None)}
    out = ["# Worked examples", "",
           "Real items from the development split: what the model saw, what it answered, what the exact oracle "
           "says, and how the answer was scored. Each example is the first item, in sorted id order, that meets the "
           "stated condition, so none was hand-picked. Long computational task descriptions are shortened with […].",
           "Generated by `experiments/make_examples.py` from the raw responses.", ""]

    # 1. over-intervention on a newly sufficient state
    rows = {r["instance_id"]: r for r in load_results(RAW, "plan_t1", Q35) if r["instance_id"] in t1}
    scored = {r["instance_id"]: r for r in pilot.score_plan_results(t1, list(rows.values()))}
    for i in sorted(t1):
        rec, s = t1[i], scored.get(i)
        if rec["t1"]["role"] == "B" and rec["t1"]["class_b"] == "ALREADY_SUFFICIENT" and s and s["valid"] and s["plan_formal"]:
            out.append(block("1. Acting when the question is already settled",
                             "qwen3.5-397b, native prompt, End-to-End; a counterfactual-pair state that one edit made "
                             "ALREADY_SUFFICIENT; the model's plan is not empty.", rec,
                             [("The model's answer (native)", answer(rows[i])),
                              ("EOP on the same item (the model extracts the state; the planner decides)",
                               eop_answer(rec, Q35, "extract_t1v2", extraction_prompt_v2))],
                             f"The edit was: {rec['t1']['edit']} on {rec['t1']['var']}. After it, the known values "
                             "already decide Q, so the correct plan is empty. The model still proposes an action: it re-runs "
                             "the computation for a fact that the text already lists as known. The benchmark text is "
                             "partly responsible. Its header says of every computational fact that the certified "
                             "value \"is not yet known\", the known-values line then lists one, and the action for it "
                             "is still on the menu. On dev, 11 of this model's 21 non-empty plans on such states "
                             "reveal only values already listed as known "
                             "(`results/aggregate/recertification_dev/recertification.json`). EOP returns the empty "
                             "plan because its planner treats the known-values line as authoritative."))
            break

    # 2. no deferral when nothing can help
    rows = {r["instance_id"]: r for r in load_results(RAW, "plan", Q35)
            if r["instance_id"] in dev and r["mode"] == "detection_controlled"}
    for i in sorted(rows):
        rec, p = dev[i], rows[i].get("parsed")
        if rec["oracle"]["resource_class"] == "NEITHER" and p and (p.get("decision") != "defer" or p.get("plan")):
            out.append(block("2. Not deferring when no available action can settle the question",
                             "qwen3.5-397b, native prompt, Detection-Controlled; oracle class NEITHER; the model "
                             "does not defer with an empty plan.", rec,
                             [("The model's answer (native)", answer(rows[i])),
                              ("EOP on the same item", eop_answer(rec, Q35, "extract_v2", extraction_prompt_v2))],
                             "No set of available actions is guaranteed to decide Q here. The right answer is an "
                             "empty plan and \"defer\". The model proposes actions instead."))
            break

    # 3. structured prompt breaks the answer format
    rows = {r["instance_id"]: r for r in load_results(RAW, "plan_s1", Q35)
            if r["instance_id"] in dev and r["mode"] == "detection_controlled"}
    for i in sorted(rows):
        r = rows[i]
        if r.get("parse_error") and "invalid JSON" in str(r["parse_error"]) and r.get("text"):
            txt = r["text"]
            out.append(block("3. The structured prompt breaks the answer format",
                             "qwen3.5-397b, structured obligation prompt (condition B), Detection-Controlled; the "
                             "answer could not be parsed.", dev[i],
                             [("Start of the model's visible answer", txt[:700] + (" […]" if len(txt) > 700 else "")),
                              ("Parser error", str(r["parse_error"])[:200])],
                             "The structured prompt lets the model write its reasoning before the JSON object. The "
                             "reasoning contains braces, the answer extractor takes the first brace group, and the "
                             "answer is counted as unparsed. This is a format artefact, not a reasoning error; it is "
                             "why condition B is reported both for all attempted answers and for parsed answers only."))
            break

    # 4. registered extraction prompt (v1) against the amended one (v2)
    for i in sorted(dev):
        rec = dev[i]
        a = latest_record(RAW, Job("extract", i, rec["family_id"], "extraction", extraction_prompt(rec["prompt_text"])), DS)
        b = latest_record(RAW, Job("extract_v2", i, rec["family_id"], "extraction", extraction_prompt_v2(rec["prompt_text"])), DS)
        if a and b and a.get("parsed") is None and b.get("parsed") is not None and a.get("text"):
            out.append(block("4. The registered extraction prompt fails on layout; the amended one does not",
                             "deepseek-v4-flash; the registered extraction prompt (v1) gave an invalid extraction "
                             "and the amended prompt (v2) a valid one for the same item.", rec,
                             [("Extraction with the registered prompt v1 (start)", a["text"][:600] + " […]"),
                              ("Why it was rejected", str(a.get("parse_error"))[:200]),
                              ("Extraction with the amended prompt v2 (start)", (b.get("text") or "")[:600] + " […]")],
                             "With prompt v1 the model returns the right content in a layout our reader does not "
                             "accept; prompt v1 never showed the required layout. Prompt v2 adds the layout and the "
                             "same model's extraction is accepted. This is PREREG_EOP Amendment 1: the registered "
                             "condition C mostly measured whether a model guessed our layout."))
            break

    dst = ROOT / "docs" / "EXAMPLES.md"
    dst.parent.mkdir(exist_ok=True)
    dst.write_text("\n".join(out) + "\n")
    print("wrote", dst, "with", sum(1 for x in out if x.startswith("## ")), "examples")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
